// Level scaling (shared so the UI shows exactly what the server uses).

export function monsterStats(species, level) {
  const L = Math.max(1, level | 0);
  const s = species.stats;
  return {
    maxHp: Math.round(s.hp * (1 + 0.2 * (L - 1))),
    atk: s.atk * (1 + 0.12 * (L - 1)),
    def: s.def * (1 + 0.08 * (L - 1)),
    speed: s.speed,
  };
}

// Extra conditions some rare monsters set before they can be recruited
// (beyond defeating them and paying). Returns null when met, else the reason.
// bestSwordTier: the highest tier among the swords the player owns.
export function recruitReqReason(species, profile, bestSwordTier) {
  const r = species.recruitReq;
  if (!r) return null;
  if (r.swordTier && bestSwordTier < r.swordTier) return `Needs a Tier ${r.swordTier} sword (you have Tier ${bestSwordTier}).`;
  const found = Object.keys(profile.discoveries?.species || {}).length;
  if (r.discoveries && found < r.discoveries) return `Discover ${r.discoveries} species first (you have ${found}).`;
  return null;
}

export function recruitPrice(species, level, discount = 0) {
  const base = species.price * (1 + 0.12 * (Math.max(1, level) - 1));
  return Math.max(1, Math.round(base * (1 - Math.min(0.3, Math.max(0, discount)))));
}

export function incomePerSecond(species, level) {
  return Math.round(species.income * (1 + 0.08 * (Math.max(1, level) - 1)) * 10) / 10;
}

export function defeatRewards(species, level) {
  const r = RARITIES[species.rarity] || RARITIES.common;
  return {
    xp: Math.round(12 * Math.max(1, level) * r.xp),
    money: Math.round(recruitPrice(species, level) * 0.06 + 4),
  };
}

export function perkValue(species, level) {
  return species.perk.value * (1 + 0.03 * (Math.max(1, level) - 1));
}

// A single number for comparing monsters in the UI.
export function monsterPower(species, level) {
  const st = monsterStats(species, level);
  return Math.round(st.maxHp * 0.5 + st.atk * 6 + st.def * 4 + species.stats.speed * 2);
}
